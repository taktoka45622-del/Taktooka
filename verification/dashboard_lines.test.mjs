import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {displayClock} from '../dist/display-format.js';
const source=readFileSync(new URL('../src/app.js',import.meta.url),'utf8');
const start=source.indexOf('function lineFacts('),end=source.indexOf('function renderLines(',start);
const context=vm.createContext({displayClock,lineWeek:['الأحد','الاثنين','الثلاثاء','الأربعاء','الخميس','الجمعة','السبت'],lineStateNames:{accepted:'تم قبول الخط'},linePayNames:{not_due:'الدفع بنهاية مدة الخط'},dates:v=>v||'—',money:n=>`${n} د.ع`});
vm.runInContext(source.slice(start,end),context);
const l={customer_name:'زبون',passenger_name:'راكب اختبار ثلاثي',pickup_name:'بيت',destination_name:'مدرسة',service_days:15,start_date:'2026-10-14',end_date:'2026-11-03',excluded_days:[5,6],departure:'07:00',arrival:'08:00',total_price:15000,status:'accepted',payment_status:'not_due',captain_name:'كابتن',late_count:2,paid_at:'2026-10-13T08:00:00Z',completed_days:15,missed_days:0,remaining_days:0};
const facts=new Map(context.lineFacts(l));
assert.equal(facts.get('أجور كل مدة الخط'),'15000 د.ع');
assert.equal(facts.get('الأيام المستبعدة'),'الجمعة، السبت');
assert.equal(facts.get('عدد أيام الخدمة'),15);
assert.equal(facts.get('آخر يوم خدمة'),'2026-11-03');
assert.equal(facts.get('تحذيرات التأخير'),2);
assert.equal(facts.has('front_path'),false);
assert.equal(facts.has('back_path'),false);
assert.equal(facts.get('تاريخ استلام الأجور'),'2026-10-13T08:00:00Z');
assert.equal(facts.get('أيام أُنجزت'),15);
assert.equal(facts.get('أيام لم تُنفّذ'),0);
assert.equal(facts.get('أيام متبقية'),0);
console.log('11 dashboard line details checks passed');
