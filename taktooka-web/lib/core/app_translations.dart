String uiText(
  String text, {
  String? language,
  String? gender,
  bool formatNumbers = true,
}) {
  final lang = language ?? appPreferences.language;
  String display(String value) =>
      (formatNumbers ? formatDisplayNumbers : englishDigits)(
        lang == 'ar'
            ? value
            : value
                  .replaceAll('صباحًا', lang == 'en' ? 'AM' : 'بەیانی')
                  .replaceAll('مساءً', lang == 'en' ? 'PM' : 'ئێوارە'),
      );
  if (lang == 'ar') return display(genderText(text, gender: gender));
  final feature = lineCopy(text, lang);
  if (feature != null) return display(feature);
  final copy = translatedCopy[text];
  return display(
    copy == null ? dynamicCopy(text, lang) : (lang == 'en' ? copy.$1 : copy.$2),
  );
}

