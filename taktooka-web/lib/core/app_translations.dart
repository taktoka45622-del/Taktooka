      'Used on trip\nTrip number: ${m[1]}',
      'لە گەشت بەکارهاتووە\nژمارەی گەشت: ${m[1]}',
    );
  m = RegExp(r'^ينتهي (.+) • الحد (.+)$').firstMatch(text);
  if (m != null)
    return choose(
      'Expires ${m[1]} · Limit ${m[2]}',
      'بەسەردەچێت ${m[1]} · سنوور ${m[2]}',
    );
  const notice = 'راح يوصلك إشعار من تتم الموافقة على طلبك.';
  if (text.endsWith('\n$notice'))
