      final translatedValue = translatedCopy[value];
      return '${lang == 'en' ? label.$1 : label.$2}: '
          '${translatedValue == null ? value : (lang == 'en' ? translatedValue.$1 : translatedValue.$2)}';
    }
  }
  return text;
