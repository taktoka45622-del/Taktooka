InputDecoration localizedInput(
  BuildContext context,
  InputDecoration decoration,
) {
  final lang = PreferencesScope.of(context).language;
  final gender = GenderScope.of(context);
  String? copy(String? text) =>
      text == null ? null : uiText(text, language: lang, gender: gender);
  return decoration.copyWith(
    labelText: copy(decoration.labelText),
    hintText: copy(decoration.hintText),
    helperText: copy(decoration.helperText),
    errorText: copy(decoration.errorText),
  );
}

String dynamicCopy(String text, String lang) {
  String choose(String en, String ku) => lang == 'en' ? en : ku;
  var m = RegExp(r'^باقي ([0-9]+) ثانية للقبول$').firstMatch(text);
  if (m != null)
    return choose(
      '${m[1]} seconds left to accept',
      '${m[1]} چرکە ماوە بۆ پەسەندکردن',
    );
  m = RegExp(r'^الخطوة ([0-9]+) من ([0-9]+)$').firstMatch(text);
  if (m != null)
    return choose('Step ${m[1]} of ${m[2]}', 'هەنگاوی ${m[1]} لە ${m[2]}');
  m = RegExp(r'^الوصول حوالي ([0-9]+) دقيقة · (.+)$').firstMatch(text);
  if (m != null)
    return choose(
      'About ${m[1]} min away · ${m[2]}',
      'نزیکەی ${m[1]} خولەک · ${m[2]}',
    );
  m = RegExp(r'^([0-9.]+) كم · ([0-9]+) دقيقة$').firstMatch(text);
  if (m != null)
    return choose('${m[1]} km · ${m[2]} min', '${m[1]} کم · ${m[2]} خولەک');
  m = RegExp(r'^هلا (.+)$').firstMatch(text);
  if (m != null) return choose('Hello ${m[1]}', 'سڵاو ${m[1]}');
  m = RegExp(r'^خصم (.+)$').firstMatch(text);
  if (m != null) return choose('Discount ${m[1]}', 'داشکاندن ${m[1]}');
  m = RegExp(r'^رحلة (.+)$').firstMatch(text);
  if (m != null) return choose('Trip ${m[1]}', 'گەشت ${m[1]}');
  m = RegExp(r'^الوصول خلال حوالي ([0-9]+) دقيقة$').firstMatch(text);
  if (m != null)
    return choose(
      'Arrival in about ${m[1]} min',
      'گەیشتن لە نزیکەی ${m[1]} خولەک',
    );
  m = RegExp(r'^خصم الزبون (.+)؛ تستحق الكروة كاملة$').firstMatch(text);
  if (m != null)
    return choose(
      'Customer discount ${m[1]}; you receive the full fare',
      'داشکاندنی کڕیار ${m[1]}؛ هەموو کرێکە وەردەگریت',
    );
  m = RegExp(
    r'^الاشتراك فعّال لغاية (.+)\nالكروة كلها إلك، بدون عمولة\.$',
  ).firstMatch(text);
  if (m != null)
    return choose(
      'Subscription active until ${m[1]}\nKeep the full fare, with no commission.',
      'بەشداری چالاکە تا ${m[1]}\nهەموو کرێکە بۆ تۆیە، بێ کۆمسیۆن.',
    );
  m = RegExp(r'^انتهت الرحلة واستلمت (.+) دينار كاش؟$').firstMatch(text);
