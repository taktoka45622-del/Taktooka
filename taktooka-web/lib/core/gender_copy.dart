import 'package:flutter/material.dart';

import 'package:taktooka/core/app_preferences.dart';
import 'package:taktooka/core/app_translations.dart';

final accountGender = ValueNotifier<String>('male');

String genderText(String text, {String? gender}) =>
    (gender ?? accountGender.value) == 'female'
    ? (_femaleCopy[text] ?? text)
    : text;

class GenderScope extends InheritedNotifier<ValueNotifier<String>> {
  GenderScope({super.key, required super.child})
    : super(notifier: accountGender);
  static String of(BuildContext context) =>
      context
          .dependOnInheritedWidgetOfExactType<GenderScope>()
          ?.notifier
          ?.value ??
      accountGender.value;
}

class AppText extends StatelessWidget {
  final String data;
  final bool formatNumbers;
  final TextStyle? style;
  final TextAlign? textAlign;
  final TextDirection? textDirection;
  final bool? softWrap;
  final TextOverflow? overflow;
  final int? maxLines;
  final String? semanticsLabel;
  final TextScaler? textScaler;
  const AppText(
    this.data, {
    this.formatNumbers = true,
    super.key,
    this.style,
    this.textAlign,
    this.textDirection,
    this.softWrap,
    this.overflow,
    this.maxLines,
    this.semanticsLabel,
    this.textScaler,
  });
  @override
  Widget build(BuildContext context) => Text(
    uiText(
      data,
      formatNumbers: formatNumbers,
      language: PreferencesScope.of(context).language,
      gender: GenderScope.of(context),
    ),
    style:
        Theme.of(context).brightness == Brightness.dark &&
            (style?.color == const Color(0xff111111) ||
                style?.color == Colors.black ||
                style?.color == const Color(0xff777777))
        ? (style ?? const TextStyle()).copyWith(
            fontFamily: 'Cairo',
            color: Theme.of(context).colorScheme.onSurface,
          )
        : (style ?? const TextStyle()).copyWith(fontFamily: 'Cairo'),
    textAlign: textAlign,
    textDirection: textDirection,
    softWrap: softWrap,
    overflow: overflow,
    maxLines: maxLines,
    semanticsLabel: semanticsLabel,
    textScaler: textScaler,
  );
}

